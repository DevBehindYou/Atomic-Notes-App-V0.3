/// Words only: lower case, every run of other characters one space.
String _words(String s) =>
    s.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]+'), ' ').trim();

Future<void> _pump(
  WidgetTester tester,
  Widget page, {
  ThemeData? theme,
  double width = 412,
  double height = 915,
  double textScale = 1,
  TextDirection direction = TextDirection.ltr,
  bool disableAnimations = false,
  bool settle = true,
}) async {
  tester.view.physicalSize = Size(width * 3, height * 3);
  tester.view.devicePixelRatio = 3;
  addTearDown(tester.view.resetPhysicalSize);
  addTearDown(tester.view.resetDevicePixelRatio);
  await tester.pumpWidget(MaterialApp(
    theme: theme ?? AtomicTheme.light,
    builder: (context, child) => MediaQuery(
      data: MediaQuery.of(context).copyWith(
        textScaler: TextScaler.linear(textScale),
        disableAnimations: disableAnimations,
      ),
      child: Directionality(textDirection: direction, child: child!),
    ),
    home: page,
    routes: {'/tcpage': (_) => const TCPage()},
  ));
  if (settle) await tester.pumpAndSettle();
}

/// Every text the page renders, in tree (reading) order. Not limited to the
/// list, so the same checks run against the pages as they were before.
String _shown(WidgetTester tester) => tester
    .widgetList<RichText>(find.byType(RichText))
    .map((t) => t.text.toPlainText())
    .join('\n');

/// [_shown] as words.
String _rendered(WidgetTester tester) => _words(_shown(tester));

/// Finds each of [before], in order, in [now].
void _expectInOrder(List<String> before, String now) {
  var from = 0;
  for (final text in before) {
    final at = now.indexOf(_words(text), from);
    expect(at, greaterThanOrEqualTo(0),
        reason: 'missing or out of order: "$text"');
    from = at + _words(text).length;
  }
}

/// Drags the list to its end, checking for layout errors on the way.
Future<void> _scrollToEnd(WidgetTester tester) async {
  final position =
      tester.state<ScrollableState>(find.byType(Scrollable).last).position;
  for (var i = 0; i < 200 && position.pixels < position.maxScrollExtent; i++) {
    await tester.drag(find.byType(ListView), const Offset(0, -400));
    await tester.pump();
    expect(tester.takeException(), isNull);
  }
  await tester.pumpAndSettle();
  expect(position.pixels, position.maxScrollExtent);
}

Future<void> _openFromButton(WidgetTester tester, Widget page) async {
  tester.view.physicalSize = const Size(412 * 3, 915 * 3);
  tester.view.devicePixelRatio = 3;
  addTearDown(tester.view.resetPhysicalSize);
  addTearDown(tester.view.resetDevicePixelRatio);
  await tester.pumpWidget(MaterialApp(
    theme: AtomicTheme.light,
    home: Builder(
      builder: (context) => TextButton(
        onPressed: () => Navigator.push(
            context, MaterialPageRoute<void>(builder: (_) => page)),
        child: const Text('open'),
      ),
    ),
  ));
  await tester.tap(find.text('open'));
  await tester.pumpAndSettle();
}

Finder _inList(Finder finder) =>
    find.descendant(of: find.byType(ListView), matching: finder);

