      await _pump(tester, const TCPage(), height: 20000);
      for (final heading in [
        _termsTitle,
        'Agreement to our legal terms',
        '1. The scope of the Agreement',
        '1.1 The scope of the Agreement',
        '1. Information Collected',
        '10. Contact',
      ]) {
        expect(tester.getSemantics(_inList(find.text(heading))),
            isSemantics(isHeader: true),
            reason: heading);
      }
      expect(find.bySemanticsLabel('Back'), findsOneWidget);
      semantics.dispose();
    });

    testWidgets('reduced motion shows everything at once', (tester) async {
      await _pump(tester, const TCPage(),
          disableAnimations: true, settle: false);
      await tester.pump();
      final fades = tester.widgetList<FadeTransition>(find.ancestor(
          of: find.text('Agreement to our legal terms'),
          matching: find.byType(FadeTransition)));
      // The entrance is there, already finished.
      expect(fades, isNotEmpty);
      for (final fade in fades) {
        expect(fade.opacity.value, 1);
      }
      expect(tester.hasRunningAnimations, isFalse);
    });

    testWidgets('without reduced motion the blocks rise in', (tester) async {
      await _pump(tester, const TCPage(), settle: false);
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 16));
      Iterable<double> fades() => tester
          .widgetList<FadeTransition>(find.ancestor(
              of: find.text('Agreement to our legal terms'),
              matching: find.byType(FadeTransition)))
          .map((f) => f.opacity.value);
      expect(fades().any((v) => v < 1), isTrue);
      await tester.pumpAndSettle();
      expect(fades().every((v) => v == 1), isTrue);
    });
