#!/usr/bin/env python3
"""Generate the AtomicIcons fonts and their Dart constants from Tabler Icons.

The App ships only the glyphs it names below. The source is the official
`@tabler/icons-webfont` npm package (MIT licence), pinned by version and by
the SHA-256 of its registry tarball. The tarball is not committed. Download it
once and pass its path:

    curl -sSL -o tabler.tgz \
      https://registry.npmjs.org/@tabler/icons-webfont/-/icons-webfont-3.51.0.tgz
    python3 tool/generate_atomic_icons.py --tarball tabler.tgz

Outputs, all committed:
    assets/fonts/AtomicIcons.ttf        outline icons, 1.5 stroke (Tabler "300")
    assets/fonts/AtomicIconsFilled.ttf  the few filled state icons
    assets/fonts/AtomicIcons-LICENSE.txt
    lib/theme/atomic_icons.dart

To add an icon, add its Tabler name to OUTLINE or FILLED and run again.
Requires fontTools (`pip install fonttools`).
"""

from __future__ import annotations

import argparse
import hashlib
import io
import re
import sys
import tarfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
TABLER_VERSION = "3.51.0"
TABLER_TARBALL_SHA256 = "9cc7f71fb3690eb5475177ddf089ba13aed06acc54095f5d2a16809d66962998"

# Outline icons. Keep each list sorted; Dart names are the camelCase of these.
OUTLINE = sorted({
    "adjustments-horizontal", "alert-circle", "alert-triangle", "archive",
    "arrow-back-up", "arrow-left", "arrow-right", "arrows-exchange", "bell",
    "bold", "bolt", "brand-google", "calendar", "camera", "check",
    "checklist", "chevron-down", "chevron-left", "chevron-right",
    "chevron-up", "circle", "circle-check", "clock", "cloud", "cloud-check",
    "cloud-off", "cloud-upload", "coin", "copy", "device-desktop",
    "device-mobile", "devices", "dots", "dots-vertical", "download", "edit",
    "external-link", "eye", "eye-off", "file-text", "filter", "fingerprint",
    "hash", "help-circle", "highlight", "history", "info-circle", "italic",
    "key", "letter-t", "link", "list-check", "lock", "lock-open", "logout",
    "mail", "microphone", "moon", "note", "notes", "palette", "pencil",
    "photo", "photo-plus", "pin", "pinned-off", "player-stop", "plus",
    "qrcode", "refresh", "restore", "search", "settings", "share",
    "shield-check", "shield-lock", "sort-ascending", "sort-descending",
    "star", "strikethrough", "sun", "tag", "trash", "trash-x", "underline",
    "upload", "user", "user-circle", "x",
})

# Filled glyphs for on states (pinned, important) and solid status dots.
FILLED = sorted({"circle", "pin", "star"})

RULE = re.compile(r"\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*\"\\([0-9a-f]+)\";")


def read_member(archive: tarfile.TarFile, name: str) -> bytes:
    member = archive.extractfile(f"package/{name}")
    if member is None:
        raise SystemExit(f"missing {name} in tarball")
    return member.read()


def codepoints(css: str) -> dict[str, int]:
    return {name: int(hex_, 16) for name, hex_ in RULE.findall(css)}


def subset_font(font_bytes: bytes, wanted: dict[str, int], family: str) -> bytes:
    font = TTFont(io.BytesIO(font_bytes), recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.recalc_timestamp = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(wanted.values()))
    subsetter.subset(font)
    # A distinct family name avoids any clash with a system Tabler install.
    for record in font["name"].names:
        if record.nameID in (1, 4, 16):
            record.string = family
        elif record.nameID == 6:
            record.string = family.replace(" ", "")
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def dart_name(name: str) -> str:
    head, *rest = name.split("-")
    ident = head + "".join(part.capitalize() for part in rest)
    if ident[0].isdigit():
        ident = "i" + ident
    return ident


def dart_source(outline: dict[str, int], filled: dict[str, int]) -> str:
    lines = [
        "// GENERATED by tool/generate_atomic_icons.py. Do not edit by hand.",
        f"// Source: @tabler/icons-webfont {TABLER_VERSION} (MIT licence).",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// Tabler outline icons (1.5 stroke) bundled as the AtomicIcons font.",
        "///",
        "/// Every value is a compile-time constant, so release builds keep only",
        "/// the glyphs actually referenced.",
        "abstract final class AtomicIcons {",
        "  static const String fontFamily = 'AtomicIcons';",
        "  static const String filledFontFamily = 'AtomicIconsFilled';",
        "",
    ]
    for name in OUTLINE:
        lines.append(
            f"  static const IconData {dart_name(name)} = "
            f"IconData(0x{outline[name]:x}, fontFamily: fontFamily);"
        )
    lines.append("")
    for name in FILLED:
        lines.append(
            f"  static const IconData {dart_name(name)}Filled = "
            f"IconData(0x{filled[name]:x}, fontFamily: filledFontFamily);"
        )
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tarball", required=True, type=Path)
    args = parser.parse_args()

    raw = args.tarball.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != TABLER_TARBALL_SHA256:
        raise SystemExit(
            f"tarball SHA-256 {digest} does not match pinned "
            f"{TABLER_TARBALL_SHA256} for {TABLER_VERSION}"
        )

    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as archive:
        outline_css = read_member(archive, "dist/tabler-icons-300.css").decode()
        filled_css = read_member(archive, "dist/tabler-icons-filled.css").decode()
        outline_ttf = read_member(archive, "dist/fonts/tabler-icons-300.ttf")
        filled_ttf = read_member(archive, "dist/fonts/tabler-icons-filled.ttf")
        licence = read_member(archive, "LICENSE").decode()

    outline_map = codepoints(outline_css)
    filled_map = codepoints(filled_css)
    missing = [n for n in OUTLINE if n not in outline_map]
    missing += [f"{n} (filled)" for n in FILLED if n not in filled_map]
    if missing:
        raise SystemExit("unknown Tabler icons: " + ", ".join(missing))

    outline = {n: outline_map[n] for n in OUTLINE}
    filled = {n: filled_map[n] for n in FILLED}

    fonts = ROOT / "assets" / "fonts"
    (fonts / "AtomicIcons.ttf").write_bytes(
        subset_font(outline_ttf, outline, "AtomicIcons"))
    (fonts / "AtomicIconsFilled.ttf").write_bytes(
        subset_font(filled_ttf, filled, "AtomicIconsFilled"))
    (fonts / "AtomicIcons-LICENSE.txt").write_text(
        f"AtomicIcons.ttf and AtomicIconsFilled.ttf are subsets of\n"
        f"@tabler/icons-webfont {TABLER_VERSION} (https://tabler.io/icons).\n\n"
        + licence,
        encoding="utf-8", newline="\n")
    (ROOT / "lib" / "theme" / "atomic_icons.dart").write_text(
        dart_source(outline, filled), encoding="utf-8", newline="\n")
    print(f"{len(outline)} outline and {len(filled)} filled icons written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
