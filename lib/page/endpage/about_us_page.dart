class _AppInfoState extends State<AppInfo> {
  final ScrollController _scroll = ScrollController();

  /// The collapsed header title shows once the large title has scrolled away.
  final ValueNotifier<bool> _titleAway = ValueNotifier(false);

  @override
  void initState() {
    super.initState();
    _scroll.addListener(() => _titleAway.value =
        _scroll.hasClients && _scroll.offset > AtomicSpace.x10);
  }

  @override
  void dispose() {
    _scroll.dispose();
    _titleAway.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final c = context.colors;
    final margin = AtomicSpace.screenMargin(MediaQuery.sizeOf(context).width);
    return Scaffold(
      backgroundColor: c.canvas,
      body: SafeArea(
        bottom: false,
        child: EntranceGroup(
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              ValueListenableBuilder<bool>(
                valueListenable: _titleAway,
                builder: (context, away, _) =>
                    AtomicPageHeader(title: AppInfo.title, showTitle: away),
              ),
              Expanded(
                child: ListView(
                  controller: _scroll,
                  padding: EdgeInsets.fromLTRB(margin, 0, margin,
                      AtomicSpace.x8 + MediaQuery.paddingOf(context).bottom),
                  children: [
                    const Entrance(index: 0, child: PageTitle(AppInfo.title)),
                    const SizedBox(height: AtomicSpace.x6),
                    const Entrance(index: 1, child: _Masthead()),
                    const SizedBox(height: AtomicSpace.sectionGap),
                    Entrance(
                      index: 2,
                      child: _TextGroup(label: 'Overview', children: [
                        const _Paragraph(_intro),
                        const _Heading('Our Vision'),
                        const _Paragraph(_vision),
                        const _Heading('Key Features'),
                        for (final f in _features) _ClauseBlock(f),
                        const _Heading('Join Us on this Secure Journey'),
                        const _Paragraph(_join),
                        const _Paragraph(_thanks),
                        const _Paragraph(_osNote, note: true),
                      ]),
                    ),
                    const SizedBox(height: AtomicSpace.sectionGap),
                    Entrance(
                      index: 3,
                      child: SettingsGroup(label: 'Links', children: [
                        SettingsRow(
                          key: const ValueKey('app-info-terms'),
                          icon: AtomicIcons.fileText,
                          title: 'Terms and conditions',
                          onTap: () => Navigator.pushNamed(context, '/tcpage'),
                        ),
                      ]),
                    ),
                    const SizedBox(height: AtomicSpace.sectionGap),
                    Entrance(
                      index: 4,
                      child: _TextGroup(
                        label: 'App License Agreement',
                        children: [
                          const _Paragraph(_licenseIntro),
                          for (final clause in _license) _ClauseBlock(clause),
                          for (final line in _licenseClosing) _Paragraph(line),
                        ],
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

/// The brand mark, the name, the tagline, and the version and build.
class _Masthead extends StatelessWidget {
  const _Masthead();

  @override
  Widget build(BuildContext context) {
    final c = context.colors;
    return Column(
      key: const ValueKey('app-info-masthead'),
      children: [
        AtomicBrandMark(
            size: AtomicSpace.x16 + AtomicSpace.x2, onDark: c.isDark),
        const SizedBox(height: AtomicSpace.x3),
        Semantics(
          header: true,
          child: Text(
            'Atomic Notes',
            textAlign: TextAlign.center,
            style: AtomicType.titleLarge.copyWith(color: c.textPrimary),
          ),
        ),
        const SizedBox(height: AtomicSpace.x1),
        Text(
          _tagline,
          textAlign: TextAlign.center,
          style: AtomicType.bodyMedium.copyWith(color: c.textSecondary),
        ),
        const SizedBox(height: AtomicSpace.x2),
        Text(
          AppInfoText.versionLabel,
          key: const ValueKey('app-info-version'),
          textAlign: TextAlign.center,
          style: AtomicType.bodySmall.copyWith(color: c.textSecondary),
        ),
        Text(
          AppInfoText.copyright,
          textAlign: TextAlign.center,
          style: AtomicType.bodySmall.copyWith(color: c.textSecondary),
        ),
      ],
    );
  }
}

/// A labelled card of reading text, built on [SettingsGroup] so its label
/// and surface match the other groups.
class _TextGroup extends StatelessWidget {
  const _TextGroup({required this.label, required this.children});

  final String label;
  final List<Widget> children;

  @override
  Widget build(BuildContext context) {
    return SettingsGroup(label: label, children: [
      Padding(
        padding: const EdgeInsets.fromLTRB(AtomicSpace.cardPadding,
            AtomicSpace.cardPadding, AtomicSpace.cardPadding, 0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: children,
        ),
      ),
    ]);
  }
}

class _Heading extends StatelessWidget {
  const _Heading(this.text);

  final String text;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding:
          const EdgeInsets.only(top: AtomicSpace.x2, bottom: AtomicSpace.x2),
      child: Semantics(
        header: true,
        child: Text(
          text,
          style: AtomicType.titleMedium
              .copyWith(color: context.colors.textPrimary),
        ),
      ),
    );
  }
}

class _Paragraph extends StatelessWidget {
  const _Paragraph(this.text, {this.note = false});

  final String text;

  /// A footnote: smaller and secondary.
  final bool note;

  @override
  Widget build(BuildContext context) {
    final c = context.colors;
    return Padding(
      padding: const EdgeInsets.only(bottom: AtomicSpace.cardPadding),
      child: Text(
        text,
        style: note
            ? AtomicType.bodySmall.copyWith(color: c.textSecondary)
            : AtomicType.bodyMedium.copyWith(color: c.textPrimary),
      ),
    );
  }
}

class _ClauseBlock extends StatelessWidget {
  const _ClauseBlock(this.clause);

  final _Clause clause;

  @override
  Widget build(BuildContext context) {
    final c = context.colors;
    return Padding(
      padding: const EdgeInsets.only(bottom: AtomicSpace.cardPadding),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Semantics(
            header: true,
            child: Text(
              clause.lead,
              style: AtomicType.bodyMedium
                  .copyWith(color: c.textPrimary, fontWeight: FontWeight.w600),
            ),
          ),
          for (final line in clause.lines)
            Padding(
              padding: const EdgeInsets.only(top: AtomicSpace.x1),
              child: Text(
                line,
                style: AtomicType.bodyMedium.copyWith(color: c.textPrimary),
              ),
            ),
        ],
      ),
    );
  }
}
